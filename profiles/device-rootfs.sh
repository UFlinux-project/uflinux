#!/bin/sh
# Rootfs preparation for UFLinux device images. Runs inside the arch chroot
# after the repositories and signing key are in place, and before the disk
# image is assembled. It installs the package set, configures the installed
# (non-live) system, regenerates the initramfs without a modloop, and stages
# the boot partition contents that scripts/builder.py later copies into the
# FAT partition.
#
# Required environment: UFLINUX_DEVICE UFLINUX_ARCH UFLINUX_BOOT
# UFLINUX_SERIAL UFLINUX_CMDLINE UFLINUX_ROOT_PARTUUID UFLINUX_PACKAGES
# UFLINUX_ESP UFLINUX_VERSION UFLINUX_ROOTFS. Optional:
# UFLINUX_INITRAMFS_COMPRESSION (defaults to zstd), UFLINUX_NURA_PACKAGES
# (with UFLINUX_NURA_REPOSITORY), UFLINUX_DTBLOADER, UFLINUX_INITRAMFS_FILES,
# UFLINUX_INITRAMFS_MODULES, and the device tree the boot loader is told about:
# UFLINUX_DTB for extlinux, UFLINUX_DEVICETREE for GRUB.
set -eu
# shellcheck source=aports/uflinux/uflinux-boot-menu
. /usr/libexec/uflinux-boot-menu

device="$UFLINUX_DEVICE"
arch="$UFLINUX_ARCH"
boot="$UFLINUX_BOOT"
serial="$UFLINUX_SERIAL"
cmdline="$UFLINUX_CMDLINE"
root_partuuid="$UFLINUX_ROOT_PARTUUID"
esp="$UFLINUX_ESP"
version="$UFLINUX_VERSION"
rootfs="$UFLINUX_ROOTFS"
initramfs_compression="${UFLINUX_INITRAMFS_COMPRESSION:-zstd}"
case "$initramfs_compression" in
gzip|zstd) ;;
*) echo "device-rootfs: unsupported initramfs compression $initramfs_compression" >&2; exit 1;;
esac

# Device images boot from an installed root, so the feature set of the ISO is
# wrong here: cdrom and raid pull in drivers no supported board uses, and
# uflinux-plymouth drags the splash into an initramfs that has nothing to show
# while the root filesystem is still being located. The root filesystem
# feature matches the one scripts/builder.py formats, so the initramfs can
# mount it without probing.
features="base $rootfs phy mmc usb scsi nvme ata virtio kms"
# An F2FS root can only be grown while it is unmounted, so the resize happens
# here in the initramfs instead of in the first-boot service. The stock f2fs
# feature only carries the kernel module; this one adds the userspace the
# resize hook runs (growpart, sfdisk, partx, resize.f2fs).
if [ "$rootfs" = f2fs ]; then
	features="$features uflinux-f2fs-resize"
fi

# The mkinitfs trigger fires on every /lib/modules change and would build an
# initramfs from the ISO feature set (and abort the transaction if that
# failed), so the trigger is disabled and the initramfs is generated below.
#
# custom_files carries two kinds of payload. The board's UFLINUX_INITRAMFS_FILES
# are firmware that mkinitfs cannot discover on its own: it collects firmware by
# scanning the .ko files it copies in, so firmware wanted by a driver that is
# built into the kernel has no other way in. The rest are the files the splash
# wrapper passed to -i needs in order to boot: -i replaces /init but never
# copies Alpine's own initramfs-init, which on the ISO comes from the
# uflinux-plymouth feature that is deliberately not used here. Without it the
# wrapper execs a missing file, init dies, and the kernel panics with nothing on
# the display. The helpers are listed with it so that the hooks the wrapper
# injects resolve rather than failing at every boot stage; they stay inert
# without plymouth, which the device initramfs does not carry, and the resize
# hook exits on its own for a filesystem that cannot be grown offline.
initramfs_boot_files="usr/share/mkinitfs/initramfs-init usr/libexec/uflinux-initramfs-splash usr/libexec/uflinux-bootsplash usr/libexec/uflinux-initramfs-resize"
# Files this profile generates itself and mkinitfs has to copy in, as opposed to
# the installed ones above. Set once the package set is in place.
initramfs_generated_files=""
write_mkinitfs_conf() {
	mkdir -p /etc/mkinitfs
	cat > /etc/mkinitfs/mkinitfs.conf <<EOF
# Generated by profiles/device-rootfs.sh for the $device image.
disable_trigger=yes
features="$features"
custom_files="${UFLINUX_INITRAMFS_FILES:+$UFLINUX_INITRAMFS_FILES }${initramfs_generated_files:+$initramfs_generated_files }$initramfs_boot_files"
EOF
}

write_mkinitfs_conf

# shellcheck disable=SC2086
apk add --no-progress $UFLINUX_PACKAGES
/usr/libexec/uflinux-image-user

# Fetch the Qualcomm EFI fixup driver without adding the Nura repository to
# the solver. Nura also publishes a conflicting mkinitfs implementation.
if [ -n "${UFLINUX_NURA_PACKAGES:-}" ]; then
	# shellcheck disable=SC2086
	for package in $UFLINUX_NURA_PACKAGES; do
		apk fetch --quiet --stdout --repository "$UFLINUX_NURA_REPOSITORY" "$package" |
			tar -C / -xz
	done
fi

# mkinitfs owns /etc/mkinitfs/mkinitfs.conf and ships no protect entry for it,
# so the package install above may have replaced the file written earlier.

# A board's display chain is usually built out of loadable drivers that nothing
# loads early: this kernel has no simpledrm, and mdev only forwards devices it
# sees after the initramfs starts, so a bridge registered before that stays
# dark. initramfs-init modprobes every line of /etc/modules before it looks for
# the root device, which is what brings a console up. The kms feature already
# copies these .ko files in; the list is what loads them. No package owns
# /etc/modules, so writing it here is safe, and the installed system loads the
# same set at boot.
if [ -n "${UFLINUX_INITRAMFS_MODULES:-}" ]; then
	{
		printf '# Generated by profiles/device-rootfs.sh for the %s image.\n' "$device"
		printf '# Loaded by the initramfs, before the root filesystem is mounted.\n'
		# shellcheck disable=SC2086
		printf '%s\n' $UFLINUX_INITRAMFS_MODULES
	} > /etc/modules
	initramfs_generated_files="etc/modules"
fi

write_mkinitfs_conf

# One kernel per device image; the package set is what selects it.
kversion=$(ls /lib/modules)
[ -n "$kversion" ] || {
	echo "device-rootfs: no kernel modules installed for $device" >&2
	exit 1
}
if [ "$(printf '%s\n' "$kversion" | wc -l)" != 1 ]; then
	echo "device-rootfs: expected exactly one kernel for $device, got: $kversion" >&2
	exit 1
fi
kflavor=${UFLINUX_KERNEL_FLAVOR:?}
case "$kversion" in *-"$kflavor") ;; *) echo "Unexpected kernel ABI: $kversion" >&2; exit 1 ;; esac

depmod -a "$kversion"

# The marker is what arms the first-boot partition growth; the packaged
# default says "generic" so the service stays inert on installed systems.
mkdir -p /etc/uflinux
printf '%s\n' "$device" > /etc/uflinux/device

printf '%s\n' "uflinux-$device" > /etc/hostname

# An installed system has no live-session getty, so the serial console is
# configured from the board description instead of the architecture default.
cat > /etc/inittab <<EOF
::sysinit:/sbin/openrc sysinit
::sysinit:/sbin/openrc boot
::wait:/sbin/openrc default
tty1::respawn:/sbin/getty 38400 tty1
tty2::respawn:/sbin/getty 38400 tty2
$serial::respawn:/sbin/getty -L 115200 $serial vt100
# Stuff to do for the 3-finger-virtue key sequence.
# NOTE: all of the below must be on one line
::ctrlaltdel:/sbin/reboot
::shutdown:/sbin/openrc shutdown
EOF

# OpenRC does not enable services on install, so the boot order is written
# out here. It matches the ISO profile minus the live-session plumbing
# (modloop, splash handoff, uflinux-live) plus the device resize service.
# Not called "enable": ShellCheck reserves that name for the bash builtin and
# reports SC3044 in a POSIX sh script.
enable_service() {
	runlevel="$1"
	shift
	mkdir -p "/etc/runlevels/$runlevel"
	for service in "$@"; do
		[ -e "/etc/init.d/$service" ] || continue
		ln -sf "/etc/init.d/$service" "/etc/runlevels/$runlevel/$service"
	done
}

enable_service sysinit uflinux-splash devfs dmesg udev udev-trigger udev-settle hwdrivers
enable_service boot hwclock modules sysctl hostname bootmisc syslog uflinux-device uflinux-zram gsr-kms-capability
enable_service default uflinux-splash-stop dbus elogind iwd connman connman-vpn bluetooth tlp uflinux-acpid uflinux-routes greetd
mkdir -p /etc/runlevels/tty
for service in /etc/runlevels/default/*; do
	[ "${service##*/}" = greetd ] || cp -P "$service" /etc/runlevels/tty/
done
enable_service shutdown killprocs mount-ro

# A firmware, module list or splash repackaging that loses one of these files
# would otherwise vanish from the initramfs silently, so make it a build
# failure.
# shellcheck disable=SC2086
for file in ${UFLINUX_INITRAMFS_FILES:-} $initramfs_generated_files $initramfs_boot_files; do
	[ -f "/$file" ] || {
		echo "device-rootfs: $device needs /$file in its initramfs, but it is not there" >&2
		exit 1
	}
done

# The initramfs is built by hand rather than through update-kernel: the
# --media option that update-kernel always passes is what produces the
# squashfs modloop, and a device image has no modloop.
rm -f "/boot/initramfs-$kflavor"
# shellcheck disable=SC2086
/sbin/mkinitfs -q -b / -C "$initramfs_compression" -F "$features" \
	-i /project/aports/uflinux/uflinux-initramfs-init \
	-o "/boot/initramfs-$kflavor" "$kversion"

# GRUB needs the uncompressed EFI stub from gzip-wrapped ARM64 images.
mkdir -p "$esp/boot"
kernel_image="/boot/vmlinuz-$kflavor"
if [ "$boot" = efi ] && [ "$arch" = aarch64 ] &&
	[ "$(head -c 2 "$kernel_image")" != MZ ]; then
	gzip -dc "$kernel_image" > "$esp/boot/vmlinuz"
	[ "$(head -c 2 "$esp/boot/vmlinuz")" = MZ ]
else
	cp -a "$kernel_image" "$esp/boot/vmlinuz"
fi
cp -a "/boot/initramfs-$kflavor" "$esp/boot/initramfs"

dtb_dir="/boot/dtbs-$kflavor"
if [ -d "$dtb_dir" ]; then
	mkdir -p "$esp/dtbs"
	cp -a "$dtb_dir/." "$esp/dtbs/"
fi

# The root is found by filesystem UUID rather than device name, and has to be
# handed over read-only for filesystem checks. OpenRC's
# root service subsequently remounts it read-write. Its
# type is stated explicitly so the kernel does not have to guess, which also
# matches the single filesystem feature in the initramfs. The framebuffer
# console comes last: Alpine uses the last console= for switch_root -c, so
# userspace output stays visible when the serial console is not wired up.
# All root formatters use the root partition GUID as the filesystem UUID too.
# Alpine passes root= to BusyBox mount, which resolves UUID= and LABEL= but
# not PARTUUID=. Kernel PARTUUID support cannot resolve a userspace mount.
rootargs="root=UUID=$root_partuuid rootwait rootfstype=$rootfs rootflags=ro"
# An F2FS volume mounted without compress_algorithm= never compresses, however
# it was formatted, so the option has to be on the kernel command line: the
# initramfs hands rootflags= to mount verbatim and there is no fstab involved.
# The builder formats the volume with the matching on-disk features, and the
# kernel rejects this option on a volume that lacks them.
if [ -n "${UFLINUX_F2FS_COMPRESS:-}" ]; then
	rootargs="$rootargs,compress_algorithm=$UFLINUX_F2FS_COMPRESS,compress_mode=fs"
fi
case "$cmdline" in
*console=*) consoleargs="" ;;
*) consoleargs=" console=$serial,115200n8 console=tty0" ;;
esac

case "$boot" in
efi|pc)
	case "$arch" in
		x86_64) platform=x86_64-efi; fallback=BOOTX64.EFI ;;
		aarch64) platform=arm64-efi; fallback=BOOTAA64.EFI ;;
		*) exit 1 ;;
	esac
	mkdir -p "$esp/EFI/BOOT" "$esp/boot/grub/themes"
	cp -a /usr/share/uflinux/grub-theme "$esp/boot/grub/themes/uflinux"
	initrds=""
	for image in amd-ucode intel-ucode; do
		[ -f "/boot/$image.img" ] || continue
		cp -a "/boot/$image.img" "$esp/boot/$image.img"
		initrds="$initrds/boot/$image.img "
	done
	dtb=""
	if [ -n "${UFLINUX_DEVICETREE:-}" ]; then
		dtb="/dtbs/$UFLINUX_DEVICETREE"
		test -f "$esp$dtb"
	fi
	if [ -n "${UFLINUX_DTBLOADER:-}" ]; then
		mkdir -p "$esp/EFI/uflinux"
		cp "$UFLINUX_DTBLOADER" "$esp/EFI/uflinux/dtbloader.efi"
	fi
	if [ -f /opt/uflinux/memtest86plus ] && [ -z "$dtb" ]; then
		cp /opt/uflinux/memtest86plus "$esp/boot/grub/"
	fi
	grub_menu /boot/vmlinuz "${initrds}/boot/initramfs" "$dtb" \
		"$cmdline$consoleargs $rootargs" /boot/grub > "$esp/boot/grub/grub.cfg"
	touch "$esp/boot/grub/$root_partuuid"
	early=/tmp/uflinux-grub-early.cfg
	printf '%s\n' "search --file --set=root /boot/grub/$root_partuuid" > "$early"
	set -- -O "$platform"
	if [ -n "${UFLINUX_DTBLOADER:-}" ]; then
		set -- "$@" -d /opt/uflinux/grub-q6a/grub-core
		printf '%s\n' 'insmod chain' 'uflinux_efi_driver /EFI/uflinux/dtbloader.efi' \
			'set uflinux_dt_fixup=1' 'export uflinux_dt_fixup' >> "$early"
	fi
	printf '%s\n' 'configfile /boot/grub/grub.cfg' >> "$early"
	grub-mkstandalone --locales="" --fonts="" "$@" -o "$esp/EFI/BOOT/$fallback" \
		"boot/grub/grub.cfg=$early"
	;;
rpi)
	# The VideoCore firmware reads the kernel, initramfs, device tree and
	# overlays from this FAT partition, so everything has to be reachable
	# from its root with the paths used in config.txt.
	printf '%s\n' \
		'disable_splash=1' \
		'disable_overscan=1' \
		'arm_64bit=1' \
		'enable_uart=1' \
		'kernel=kernel8.img' \
		'initramfs boot/initramfs followkernel' \
		'include usercfg.txt' > "$esp/config.txt"
	printf 'UFLinux board overrides. This file is not replaced on upgrade.\n' \
		> "$esp/usercfg.txt"
	printf '%s\n' "$(boot_arguments standard "$cmdline$consoleargs $rootargs")" > "$esp/cmdline.txt"
	for mode in debug tty; do
		printf '%s\n' "$(boot_arguments "$mode" "$cmdline$consoleargs $rootargs")" > "$esp/cmdline-$mode.txt"
	done

	# The firmware blobs are packaged for an update tool rather than for a
	# boot partition layout, so they are unpacked straight out of the APKs.
	for package in raspberrypi-bootloader-common raspberrypi-bootloader; do
		apk fetch --quiet --stdout "$package" |
			tar -C "$esp" -xz --strip=1 boot/
	done
	cp -a /boot/kernel8.img "$esp/kernel8.img"
	cp -a "$dtb_dir"/broadcom/*.dtb "$esp/"
	mkdir -p "$esp/overlays"
	cp -a "$dtb_dir"/overlays/. "$esp/overlays/"

	;;
extlinux)
	# U-Boot distro boot reads this file, so the board's existing bootloader
	# is reused instead of shipping a second stage.
	[ -n "${UFLINUX_DTB:-}" ] || {
		echo "device-rootfs: $device needs a device tree path for extlinux" >&2
		exit 1
	}
	[ -f "$esp/dtbs/$UFLINUX_DTB" ] || {
		echo "device-rootfs: $esp/dtbs/$UFLINUX_DTB is missing" >&2
		exit 1
	}
	mkdir -p "$esp/extlinux"
	{
		printf 'TIMEOUT 30\n'
		printf 'DEFAULT uflinux-standard\n'
		for board in uflinux orangepi-r2s bananapi-f3; do
		for mode in $boot_modes; do
			printf 'LABEL %s-%s\n' "$board" "$mode"
			case "$board" in
				uflinux) label="Orange Pi RV2"; dtb="$UFLINUX_DTB" ;;
				orangepi-r2s) label="Orange Pi R2S"; dtb="ky/x1_orangepi-r2s.dtb" ;;
				bananapi-f3) label="Banana Pi F3 (firmware DTB, unverified)"; dtb="" ;;
			esac
			printf '\tMENU LABEL UFLinux %s (%s, %s)\n' "$version" "$label" "$(boot_label "$mode")"
			printf '\tLINUX /boot/vmlinuz\n\tINITRD /boot/initramfs\n'
			if [ -n "$dtb" ]; then
				[ -f "$esp/dtbs/$dtb" ] || exit 1
				printf '\tFDT /dtbs/%s\n' "$dtb"
			fi
			printf '\tAPPEND %s\n' "$(boot_arguments "$mode" "$cmdline$consoleargs $rootargs")"
		done
		done
	} > "$esp/extlinux/extlinux.conf"
	;;
*)
	echo "device-rootfs: unsupported boot mode $boot" >&2
	exit 1
	;;
esac
